// Finds a valid seed for every track slot and writes src/data/tracks.js.
//   npm run tracks
// Re-run after changing the generator, the chapter styles or the car handling.
// A candidate is accepted when: geometry checks pass (radius, width, length, wall clearance)
// AND a drift-style bot AND a cautious grip-style bot can both finish without ever leaving the road
// (leaving the road ends a run), and the drift bot must actually drift a fair share of the lap.

import { writeFileSync } from 'node:fs';
import { CHAPTERS } from '../src/data/chapters.js';
import { generateTrack, paramsFor } from '../src/tracks/generator.js';
import { Track } from '../src/tracks/Track.js';
import { checkGeometry, botLap } from '../src/tracks/validate.js';
import { mulberry32 } from '../src/rng.js';

const slots = [];
CHAPTERS.forEach((_, c) => { for (let l = 0; l < 10; l++) slots.push({ kind: 'career', c, l, id: `c${c + 1}l${l + 1}` }); });
CHAPTERS.forEach((_, c) => slots.push({ kind: 'gp', c, l: 0, id: `gp${c + 1}` }));

const used = new Set();
function nameFor(slot, seed) {
  const nm = CHAPTERS[slot.c].names;
  const rnd = mulberry32(seed * 7919 + slot.c * 131 + slot.l);
  for (let tries = 0; tries < 400; tries++) {
    let n;
    if (rnd() < 0.12) n = nm.solo[Math.floor(rnd() * nm.solo.length)];
    else n = `${nm.first[Math.floor(rnd() * nm.first.length)]} ${nm.second[Math.floor(rnd() * nm.second.length)]}`;
    if (!used.has(n)) { used.add(n); return n; }
  }
  throw new Error('out of names for ' + slot.id);
}

const out = [];
let tries = 0;
for (const [idx, slot] of slots.entries()) {
  const P = paramsFor(slot.kind, slot.c, slot.l);
  let found = null;
  for (let k = 0; k < 2500 && !found; k++) {
    const seed = 1000 * (idx + 1) + k;
    tries++;
    const g = generateTrack(P, seed);
    const track = new Track({ name: slot.id, points: g.points, width: P.width, iceZones: g.iceZones });
    const geo = checkGeometry(track);
    if (!geo.ok) continue;
    const bot = botLap(track, { driver: { style: 'drift' } });
    if (!bot.finished || bot.stuck || bot.offRoad > 0 || bot.spins > 0 || bot.driftShare < 0.08) continue;
    const safe = botLap(track, { driver: { style: 'grip', cornerEntry: 0.9 } });
    if (!safe.finished || safe.stuck || safe.offRoad > 0) continue;
    if (slot.kind === 'career' && (bot.time > 90 || bot.time < 18)) continue;
    if (slot.kind === 'gp' && (bot.time > 62 || bot.time < 28)) continue;
    found = { seed, track, geo, bot, gen: g, width: P.width };
  }
  if (!found) throw new Error('no valid seed for ' + slot.id);
  const { seed, geo, bot, gen, width } = found;
  const laps = slot.kind === 'gp' ? 3 : Math.max(1, Math.min(3, Math.round(60 / bot.time)));
  out.push({
    id: slot.id, kind: slot.kind, chapter: slot.c, level: slot.l, name: nameFor(slot, seed), seed, laps,
    length: Math.round(geo.length), minRadius: Math.round(geo.minRadius * 10) / 10, ref: Math.round(bot.time * 100) / 100,
    width: Math.round(width * 10) / 10,
    ice: gen.iceZones.map(([a, b]) => [Math.round(a * 10) / 10, Math.round(b * 10) / 10]),
    pts: gen.points.flatMap(([x, z]) => [Math.round(x * 10), Math.round(z * 10)]), // decimetres
  });
  process.stdout.write(`${slot.id} seed=${seed} len=${Math.round(geo.length)} bot=${bot.time.toFixed(1)}s laps=${laps}\n`);
}

const body = out.map((t) => '  ' + JSON.stringify(t)).join(',\n');
writeFileSync(new URL('../src/data/tracks.js', import.meta.url), `// GENERATED by tools/buildTracks.js - do not edit by hand (run \`npm run tracks\`).
// seed: generator seed (src/tracks/generator.js) - kept for reference / regeneration.
// pts: the final control points as integer decimetres [x0, z0, x1, z1, ...]: stored (not regenerated at
// runtime) so every browser gets exactly the same track. ice: [start, end] distances along the track.
// ref: drift-bot reference time (seconds, whole run of one lap). laps: laps for the career time trial.
export const TRACKS = [
${body},
];
`);
console.log(`\n${out.length} tracks written (${tries} candidates tried).`);
